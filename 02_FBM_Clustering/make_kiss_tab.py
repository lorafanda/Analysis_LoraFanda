"""
make_kiss_tab.py - the KISS tab of analysis_status.html. Keep It Simple, Stupid.

Every illustrated explanation lives here, in plain words. The other tabs explain what
was DONE; this one explains what the words MEAN, once, so a term that reads as jargon
somewhere else has exactly one place to be looked up.

The rule for adding to it: whenever an illustrated explanation of a concept is asked
for, the figure goes in outputs/clustering/explainers/ and an entry goes in ENTRIES
below. Nothing else needs touching - the nav button, the index and the section are all
generated from that list.

    python make_kiss_tab.py            # write the fragment
    python make_kiss_tab.py --insert   # AND splice it into the site

Idempotent: the splice is delimited by HTML comments, so re-running replaces the tab
rather than stacking a second one.
"""
