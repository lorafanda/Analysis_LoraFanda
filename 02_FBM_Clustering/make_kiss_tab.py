CSS = "  .nk .dot{background:#c98f00}"


def build() -> str:
    idx = " &nbsp;&middot;&nbsp; ".join(
        f'<a href="#{e["id"]}">{e["label"]}</a>' for e in ENTRIES)
    n_fig = sum(len(e["figs"]) for e in ENTRIES)

    P = [B_SEC, '  <section id="kiss">',
         '    <div class="eyebrow" style="color:#c98f00">Reference</div>',
         "    <h2>KISS &mdash; keep it simple, stupid</h2>",
         '    <div class="method" style="border-left:4px solid #c98f00">',
         "      <b>Every idea on this site, explained once, in plain words, with a "
         "picture.</b> The other tabs say what was <i>done</i>; this one says what the "
         "words <i>mean</i>. If a term reads as jargon somewhere else, it has exactly "
         "one place to be looked up, and this is it.",
         f"      <p style='margin:8px 0 0'>{n_fig} figures, "
         f"{len(ENTRIES)} topics: {idx}</p>",
         "      <p style='margin:8px 0 0;color:#68727d'>Each figure is built by a "
         "script in <code>02_FBM_Clustering/</code> and every number on it is computed "
         "rather than typed, so an explainer cannot quietly disagree with the analysis "
         "it explains. The tab itself is generated by "
         "<code>make_kiss_tab.py</code>.</p>",
         "    </div>"]

    for e in ENTRIES:
        P.append(f'    <h3 id="{e["id"]}">{e["label"]}</h3>')
        P.append('    <div class="callout q" style="margin:0 0 10px">'
                 f'<b>The question.</b> {e["q"]}</div>')
        for para in e["body"]:
            P.append(f'    <p style="margin:0 0 8px">{para}</p>')
        for num, title, img, alt in e["figs"]:
            P.append(f"""
    <figure><div class="cap"><div class="fignum">FIG {num}</div>
      <h4>{title}</h4>
      <div class="runid"><code>{FIGROOT}/{img}</code></div></div>
      <div class="imgwrap"><img data-fig="{FIGROOT}/{img}" alt="{alt}"></div>
    </figure>""")

    P += ["  </section>", E_SEC]
    return "\n".join(P)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--insert", action="store_true")
    a = ap.parse_args()

    missing = [f[2] for e in ENTRIES for f in e["figs"] if not (EXPL / f[2]).exists()]
    if missing:
        print("MISSING FIGURES - the tab would render placeholders:")
        for m in missing:
            print(f"   {m}")

    html = build()
    out = EXPL / "webblock_kiss.html"
    out.write_text(html, encoding="utf-8")
    print(f"-> {out}   ({len(html):,} chars, "
          f"{sum(len(e['figs']) for e in ENTRIES)} figures)")
    if not a.insert:
        print("\n(pass --insert to splice it into the site)")
        return 0

    s = SITE.read_text(encoding="utf-8")

    # the section
    if B_SEC in s and E_SEC in s:
        i, j = s.index(B_SEC), s.index(E_SEC) + len(E_SEC)
        s = s[:i] + html + s[j:]
        print("replaced the existing kiss section")
    else:
        anchor = '  <section id="caveats">'
        if anchor not in s:
            raise SystemExit("anchor section not found")
        i = s.index(anchor)
        s = s[:i] + html + "\n\n" + s[i:]
        print("inserted the kiss section before #caveats")

    # the nav button
    if B_NAV in s and E_NAV in s:
        i, j = s.index(B_NAV), s.index(E_NAV) + len(E_NAV)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + s[j:]
    else:
        anchor = '    <button class="n5" data-t="caveats">'
        if anchor not in s:
            raise SystemExit("nav anchor not found")
        i = s.index(anchor)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + "\n" + s[i:]
        print("inserted the nav button before Caveats")

    # the dot colour, once
    if ".nk .dot" not in s:
        a2 = "  .n10 .dot{background:var(--s5)}"
        if a2 not in s:
            raise SystemExit("css anchor not found")
        s = s.replace(a2, CSS + "\n" + a2, 1)
        print("added the .nk dot colour")

    SITE.write_text(s, encoding="utf-8")
    print(f"-> {SITE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
