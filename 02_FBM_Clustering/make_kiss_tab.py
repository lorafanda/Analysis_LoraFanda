def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--insert", action="store_true")
    a = ap.parse_args()

    missing = [f[2] for e in ENTRIES for f in e["figs"]
               if not ((ROOT.parent / f[2]) if "/" in f[2] else (EXPL / f[2])).exists()]
    if missing:
        print("MISSING FIGURES - the tab would render placeholders:")
        for m in missing:
            print(f"   {m}")

    html = build()
    out = EXPL / "webblock_kiss.html"
    out.write_text(html, encoding="utf-8")
    print(f"-> {out}   ({len(html):,} chars, "
          f"{sum(len(e['figs']) for e in ENTRIES)} figures)")
    if not a.insert:
        print("\n(pass --insert to splice it into the site)")
        return 0

    s = SITE.read_text(encoding="utf-8")

    # the section
    if B_SEC in s and E_SEC in s:
        i, j = s.index(B_SEC), s.index(E_SEC) + len(E_SEC)
        s = s[:i] + html + s[j:]
        print("replaced the existing kiss section")
    else:
        anchor = '  <section id="caveats">'
        if anchor not in s:
            raise SystemExit("anchor section not found")
        i = s.index(anchor)
        s = s[:i] + html + "\n\n" + s[i:]
        print("inserted the kiss section before #caveats")

    # the nav button
    if B_NAV in s and E_NAV in s:
        i, j = s.index(B_NAV), s.index(E_NAV) + len(E_NAV)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + s[j:]
    else:
        anchor = '    <button class="n5" data-t="caveats">'
        if anchor not in s:
            raise SystemExit("nav anchor not found")
        i = s.index(anchor)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + "\n" + s[i:]
        print("inserted the nav button before Caveats")

    # the dot colour, once
    if ".nk .dot" not in s:
        a2 = "  .n10 .dot{background:var(--s5)}"
        if a2 not in s:
            raise SystemExit("css anchor not found")
        s = s.replace(a2, CSS + "\n" + a2, 1)
        print("added the .nk dot colour")

    SITE.write_text(s, encoding="utf-8")
    print(f"-> {SITE}")
    return 0


