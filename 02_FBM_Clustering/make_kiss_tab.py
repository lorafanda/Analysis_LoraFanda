def _fig4_numbers() -> dict:
    """One real matched pair from FIG 4, so the walkthrough quotes the figure."""
    import csv, io
    figs = ROOT / "outputs" / "clustering" / "paper_figures"
    hits = sorted(figs.glob("FIG4_matched_K08_run*.csv"))
    if not hits:
        return {}
    with io.open(hits[-1], encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f)
                if r["weighting"] == "hard"
                and r["comparison"] == "cnmf_vs_kmeans_concat_hg"]
    if not rows:
        return {}
    r = min(rows, key=lambda r: abs(float(r["overlap"]) - 0.69))   # the strongest pair
    g = lambda k: float(r[k])
    return dict(c1=r["cluster_1"], c2=r["cluster_2"], r=g("r_centred"),
                n1=int(g("n_1")), n2=int(g("n_2")), j=g("overlap"),
                j0=g("null_plain_mean"), sd=g("null_plain_sd"), z=g("z_plain"),
                p=g("p_plain"), zw=g("z_within"), pw=g("p_within"),
                adj=(g("overlap") - g("null_plain_mean")) / (1 - g("null_plain_mean")),
                inter=round(g("overlap") * (g("n_1") + g("n_2")) / (1 + g("overlap"))))


