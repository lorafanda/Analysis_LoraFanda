    if BEGIN in s and END in s:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        s = s[:i] + html + s[j:]
        print("replaced the existing generated block")
    else:
        # first time: take over the hand-written region, from the statistics heading up
        # to the next figure that is not ours
        anchor = '<h4 id="s2stats">'
        stop = '<figure id="s2three">'
        hfig = '<figure id="s2heldout">'
        if hfig not in s or anchor not in s or stop not in s:
            raise SystemExit("anchors not found - splice by hand this once")
        i, j = s.index(hfig), s.index(stop)
        if not i < j:
            raise SystemExit("anchors out of order")
        s = s[:i] + html + "\n    " + s[j:]
        print("replaced the hand-written block (C.13 + statistics)")
    SITE.write_text(s, encoding="utf-8")
    print(f"-> {SITE}")
    return 0


