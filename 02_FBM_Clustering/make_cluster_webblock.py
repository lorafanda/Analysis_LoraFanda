def esc(s) -> str:
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def fmt(v, n=3, sign=False):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "&mdash;"
    return f"{v:+.{n}f}" if sign else f"{v:.{n}f}"


# ── loading ─────────────────────────────────────────────────────────────────
def discover():
    """Every {feature_set}_K{k} directory that actually has a summary in it."""
    out = []
    for d in sorted(STATS.glob("*_K*")):
        f = d / "stats_summary.json"
        if f.exists():
            out.append((d, json.loads(f.read_text())))
    # concat_hg before concat_rawds, which is the order the argument runs in
    rank = {"concat_hg": 0, "concat_rawds": 1, "concat_bands5": 2,
            "concat_bands5z": 3, "concat_hg_all": 4}
    out.sort(key=lambda t: rank.get(t[1].get("feature_set", ""), 9))
    return out


def load(d):
    g = {}
    for k, f in (("sep", "stats_separation.csv"), ("agr", "stats_agreement.csv"),
                 ("coh", "stats_coherence.csv"), ("sizes", "stats_cluster_sizes.csv"),
                 ("lopo", "stats_lopo.csv")):
        p = d / f
        g[k] = pd.read_csv(p) if p.exists() else None
    return g


# ── tables ──────────────────────────────────────────────────────────────────
def t_separation(sep):
    if sep is None:
        return "<p><i>separation not computed</i></p>"
    rows = ["<tr><th></th><th>home space</th><th>silhouette</th><th>matched null</th>"
            "<th>z (home)</th><th>z in the other space</th></tr>"]
    for m in ORDER:
        h = sep[(sep.method == m) & (sep.home)]
        o = sep[(sep.method == m) & (~sep.home)]
        if h.empty:
            continue
        h = h.iloc[0]
        o = o.iloc[0] if not o.empty else None
        z = float(h.z)
        zc = GREEN if z > 3 else (RED if z < 2 else INK)
        rows.append(
            f"<tr><td><b>{NICE[m]}</b></td><td><code>{h.space}</code></td>"
            f"<td>{fmt(h.silhouette, 4, True)}</td>"
            f"<td>{fmt(h.null_mean, 4, True)} &plusmn; {fmt(h.null_sd, 4)}</td>"
            f"<td style='color:{zc}'><b>{fmt(z, 1, True)}</b></td>"
            f"<td><i>{fmt(o.z, 1, True) if o is not None else '&mdash;'}</i></td></tr>")
    return "<table class='sum' style='margin:8px 0'>" + "".join(rows) + "</table>"


def t_agreement(agr):
    if agr is None:
        return ""
    rows = ["<tr><th>pair</th><th>ARI</th><th>NMI</th></tr>"]
    for _, r in agr.iterrows():
        rows.append(f"<tr><td>{NICE[r.a]} vs {NICE[r.b]}</td>"
                    f"<td><b>{fmt(r.ari)}</b></td><td>{fmt(r.nmi)}</td></tr>")
    return "<table class='sum' style='margin:8px 0'>" + "".join(rows) + "</table>"


def t_coherence(coh, sizes):
    if coh is None:
        return ""
    rows = ["<tr><th></th><th>neighbours sharing label</th><th>over chance</th>"
            "<th>largest cluster</th><th>smallest</th></tr>"]
    best = float(coh.over_chance.max())
    for m in ORDER:
        r = coh[coh.method == m]
        if r.empty:
            continue
        r = r.iloc[0]
        s = sizes[sizes.method == m] if sizes is not None else None
        big = int(s.n.max()) if s is not None and not s.empty else None
        small = int(s.n.min()) if s is not None and not s.empty else None
        # a python 3.11 f-string expression may not contain a backslash, so the
        # escaped quotes are precomputed rather than inlined
        style = f' style="color:{GREEN}"' if r.over_chance >= best - 1e-9 else ""
        tiny = f' style="color:{RED}"' if (small is not None and small < 10) else ""
        rows.append(f"<tr><td><b>{NICE[m]}</b></td>"
                    f"<td>{fmt(r.neighbours_sharing_label)}</td>"
                    f"<td{style}><b>{fmt(r.over_chance, 2)}&times;</b></td>"
                    f"<td>{big if big is not None else '&mdash;'}</td>"
                    f"<td{tiny}>{small if small is not None else '&mdash;'}</td></tr>")
    return "<table class='sum' style='margin:8px 0'>" + "".join(rows) + "</table>"


def t_lopo(summ):
    lp = (summ or {}).get("lopo") or {}
    if not lp:
        return ""
    rows = ["<tr><th></th><th>worst fold</th><th>size-matched null</th><th>z</th>"
            "<th>verdict</th></tr>"]
    for m in ORDER:
        s = lp.get(m)
        if not s:
            continue
        # THE SIGN CARRIES THE MEANING. Inside the null is the pass; above it is better
        # than the pass; only BELOW means one patient is holding the solution together.
        # An abs(z) test here would have printed Ward's +2.03 as a failure.
        z = float(s["z"])
        if z <= -2:
            v, c = "BELOW &mdash; a patient is carrying it", RED
        elif z >= 2:
            v, c = "above &mdash; more robust than chance", GREEN
        else:
            v, c = "inside &mdash; no patient carries it", GREEN
        rows.append(f"<tr><td><b>{NICE[m]}</b></td><td>{fmt(s['real_min'])}</td>"
                    f"<td>{fmt(s['null_min_mean'])} &plusmn; {fmt(s['null_min_sd'])}</td>"
                    f"<td>{fmt(z, 2, True)}</td>"
                    f"<td style='color:{c}'>{v}</td></tr>")
    return "<table class='sum' style='margin:8px 0'>" + "".join(rows) + "</table>"


# ── the sentences, decided from the numbers ─────────────────────────────────
def say_separation(sep):
    h = sep[sep.home].set_index("method")
    win = h.z.idxmax()
    lo = h.z.idxmin()
    s = (f"<b>{NICE[win]} separates best here (z&nbsp;=&nbsp;{h.z[win]:+.1f})</b>, "
         f"{NICE[lo]} least (z&nbsp;=&nbsp;{h.z[lo]:+.1f}).")
    weak = [m for m in ORDER if m in h.index and h.z[m] < 2]
    if weak:
        s += (" " + " and ".join(NICE[m] for m in weak) +
              (" barely clears its null" if len(weak) == 1 else " barely clear their nulls") +
              " at all.")
    o = sep[~sep.home].set_index("method")
    collapse = [m for m in ORDER if m in o.index and o.z[m] < 0]
    if len(collapse) == len(ORDER):
        s += (" <b>Every method collapses in the other's space</b> &mdash; all three "
              "cross-space z below zero &mdash; exactly as C.7 reported: they describe "
              "different structure, they do not disagree about the same structure.")
    elif collapse:
        v = "collapses" if len(collapse) == 1 else "collapse"
        s += (" " + ", ".join(NICE[m] for m in collapse) + f" {v} when scored in the "
              "other space, but not all three do here.")
    else:
        s += (" Unusually, <b>none of the three collapses in the other space</b> &mdash; "
              "every cross-space z is positive, so this feature set's structure is "
              "visible from both.")
    return s


def say_agreement(agr):
    lo, hi = float(agr.ari.min()), float(agr.ari.max())
    tone = ("agree only weakly" if hi < 0.4 else
            "agree moderately" if hi < 0.6 else "agree substantially")
    return (f"Three defensible methods on identical electrodes {tone}, at ARI "
            f"{lo:.2f}&ndash;{hi:.2f}.")


def say_coherence(coh, sizes):
    c = coh.set_index("method")
    win = c.over_chance.idxmax()
    others = [m for m in ORDER if m != win and m in c.index]
    s = (f"<b>{NICE[win]} wins on anatomy &mdash; {c.over_chance[win]:.2f}&times; "
         f"chance against " +
         " and ".join(f"{c.over_chance[m]:.2f}&times;" for m in others) + "</b>")
    if c.neighbours_sharing_label[win] <= c.neighbours_sharing_label.min() + 1e-12:
        s += (", <b>while having the LOWEST raw neighbour-sharing</b>. The chance "
              "correction is doing the work")
    s += ". "
    if sizes is not None:
        rng = {m: (int(sizes[sizes.method == m].n.min()),
                   int(sizes[sizes.method == m].n.max())) for m in ORDER
               if not sizes[sizes.method == m].empty}
        deg = [m for m, (a, _) in rng.items() if a < 10]
        if deg:
            s += ("The cluster-size columns show why: " +
                  ", ".join(f"{NICE[m]} puts {rng[m][1]} electrodes in one cluster and "
                            f"{rng[m][0]} in another" for m in deg) +
                  f", while {NICE[win]} spans {rng[win][0]}&ndash;{rng[win][1]}. "
                  "<b>A hard method can look anatomically coherent simply by having one "
                  "cluster that covers everything</b>, and the chance correction is what "
                  "takes that back.")
        else:
            s += ("No method has a degenerate cluster here &mdash; the smallest is " +
                  f"{min(a for a, _ in rng.values())} electrodes &mdash; so the ranking "
                  "is not an artefact of one cluster swallowing the cohort.")
    s += (" <b>This is the criterion that is about the brain rather than about the "
          "fit</b>: no method is given a coordinate.")
    return s


def say_lopo(summ):
    lp = (summ or {}).get("lopo") or {}
    zs = {m: float(v["z"]) for m, v in lp.items()}
    bad = [m for m, z in zs.items() if z <= -2]
    good = [m for m, z in zs.items() if z >= 2]
    if bad:
        return ("<b>" + ", ".join(NICE[m] for m in bad) + " falls BELOW the null</b> "
                "&mdash; losing that patient costs more than losing the same number of "
                "random electrodes, which is what a single patient carrying the solution "
                "looks like.")
    s = "<b>Sitting inside the null is the pass.</b> It means losing a patient costs no "
    s += "more than losing that many random electrodes. "
    if good:
        s += ("All three do, and " + " and ".join(NICE[m] for m in good) +
              " sits above it &mdash; more robust than chance.")
    else:
        s += "All three do."
    return s


