"""
make_paper_tab.py - the "Paper 2 - manuscript" tab of analysis_status.html.

    python make_paper_tab.py            print the block, change nothing
    python make_paper_tab.py --insert   splice it into the site

WHAT THIS IS. A writing scaffold for the Cell Reports submission, not prose. Every
section of the manuscript gets a subtab, every subtab a set of headed prompts, and every
prompt an empty box to write into. The prompts are questions to answer; the answers are
yours and nothing here writes them for you.

WHERE THE TEXT LIVES. In the browser, under localStorage keys `fbm.paper2.<field id>`.
That is why the field ids below are explicit slugs and not positions: THE OUTLINE CAN BE
REGENERATED, REORDERED OR EXTENDED WITHOUT LOSING A WORD, as long as an id keeps its
name. Renaming an id orphans its text - the box comes back empty and the old value stays
in localStorage - so change labels and prompts freely, and ids only on purpose.

Because the text is browser-local it is NOT in git and NOT on another machine. The tab
says so at the top, keeps a visible saved/unsaved state, and carries Export (Markdown,
copy or download) and Import (read a previously exported file back). Export is the only
thing that makes the writing durable.

EXAMPLES. Under the Introduction and the three figure sections, two example answers sit
above each box (EXAMPLES below, keyed by field id). They are drafts to react to, written
in the paper's voice with the numbers from the current run, and a "Use as draft" button
copies one into the box. Every number in them was read off the figures' CSVs and captions
when they were written; [REF] and [brackets] mark what only the author can fill.
"""
