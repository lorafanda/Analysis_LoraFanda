def splice(s, begin, end, block, anchor=None, before=True, what=""):
    """Replace a marked block, or insert it relative to `anchor` the first time."""
    if begin in s and end in s:
        i, j = s.index(begin), s.index(end) + len(end)
        return s[:i] + block + s[j:], f"replaced {what}"
    if anchor is None or anchor not in s:
        raise SystemExit(f"anchor for {what} not found - splice by hand this once")
    i = s.index(anchor)
    if before:
        return s[:i] + block + "\n" + s[i:], f"inserted {what}"
    i += len(anchor)
    return s[:i] + "\n" + block + s[i:], f"inserted {what}"


