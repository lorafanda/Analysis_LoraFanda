def G(text, sub=""):
    """A group heading inside a subtab."""
    return {"kind": "group", "h": text, "sub": sub}


def F(fid, h, prompt, rows=5, limit=None, placeholder=""):
    """One prompt and its box. `fid` is the localStorage key and must stay stable."""
    return {"kind": "field", "id": fid, "h": h, "prompt": prompt, "rows": rows,
            "limit": limit, "ph": placeholder}


def L(fid, h, prompt, limit=None, placeholder=""):
    """A one-line field - titles, names, a single sentence."""
    return {"kind": "line", "id": fid, "h": h, "prompt": prompt, "limit": limit,
            "ph": placeholder}


