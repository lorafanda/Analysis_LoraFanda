def splice(s, begin, end, block, anchor=None, before=True, what=""):
    """Replace a marked block, or insert it relative to `anchor` the first time."""
    if begin in s and end in s:
        i, j = s.index(begin), s.index(end) + len(end)
        return s[:i] + block + s[j:], f"replaced {what}"
    if anchor is None or anchor not in s:
        raise SystemExit(f"anchor for {what} not found - splice by hand this once")
    i = s.index(anchor)
    if before:
        return s[:i] + block + "\n" + s[i:], f"inserted {what}"
    i += len(anchor)
    return s[:i] + "\n" + block + s[i:], f"inserted {what}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--insert", action="store_true", help="write into the site")
    ap.add_argument("--site", default=str(SITE))
    a = ap.parse_args()

    nav, block = build()
    _isfield = lambda b: b["kind"] not in ("group", "draft")
    nfields = sum(1 for s in SECTIONS for b in s["blocks"] if _isfield(b))
    ids = [b["id"] for s in SECTIONS for b in s["blocks"] if _isfield(b)]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit(f"duplicate field ids, which would share one box: {sorted(dup)}")
    # an example keyed to a field that does not exist would silently render nowhere
    orphan = sorted(set(EXAMPLES) - set(ids))
    if orphan:
        raise SystemExit(f"EXAMPLES keyed to fields that do not exist: {orphan}")
    short = sorted(k for k, v in EXAMPLES.items() if len(v) != 2)
    if short:
        raise SystemExit(f"every field needs exactly two examples: {short}")
    nex = sum(len(v) for v in EXAMPLES.values())

    if not a.insert:
        print(block)
        print(f"\n<!-- {len(SECTIONS)} subtabs, {nfields} fields, "
              f"{nex} examples on {len(EXAMPLES)} of them -->")
        print("(pass --insert to splice it into the site)")
        return 0

    site = Path(a.site)
    if not site.exists():
        raise SystemExit(f"no {site}")
    s = site.read_text(encoding="utf-8")

    s, m1 = splice(s, NAV_BEGIN, NAV_END, nav,
                   anchor='    <button class="n5" data-t="caveats"', what="nav button")
    s, m2 = splice(s, BEGIN, END, block,
                   anchor='  <section id="caveats">', what="tab body")
    s, m3 = splice(s, CSS_BEGIN, CSS_END, CSS, anchor="</style>", what="css")
    s, m4 = splice(s, JS_BEGIN, JS_END, JS, anchor="</script>", what="js")

    site.write_text(s, encoding="utf-8")
    for m in (m1, m2, m3, m4):
        print("  " + m)
    print(f"-> {site}  ({len(SECTIONS)} subtabs, {nfields} fields, "
          f"{nex} examples on {len(EXAMPLES)} of them)")
    return 0


