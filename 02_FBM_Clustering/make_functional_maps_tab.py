def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--insert", action="store_true")
    a = ap.parse_args()
    html = build()
    (OUT / "webblock_functional_maps.html").write_text(html, encoding="utf-8")
    mb = sum(f.stat().st_size for f in OUT.glob("*.webp")) / 1e6
    print(f"-> {OUT}   {len(SOURCES)} copies, {mb:.1f} MB")
    if not a.insert:
        print("(pass --insert to splice it into the site)")
        return 0
    s = SITE.read_text(encoding="utf-8")
    if B_SEC in s and E_SEC in s:
        i, j = s.index(B_SEC), s.index(E_SEC) + len(E_SEC)
        s = s[:i] + html + s[j:]
        print("replaced the existing functional maps section")
    else:
        anchor = '  <section id="caveats">'
        if anchor not in s:
            raise SystemExit("anchor section not found")
        i = s.index(anchor)
        s = s[:i] + html + "\n\n" + s[i:]
        print("inserted the functional maps section before #caveats")
    if 'data-t="fmaps"' not in s:
        anchor = '    <button class="n5" data-t="caveats">'
        if anchor not in s:
            raise SystemExit("nav anchor not found")
        i = s.index(anchor)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + "\n" + s[i:]
    SITE.write_text(s, encoding="utf-8")
    print(f"-> {SITE}   (now: python make_site_ui.py --insert, then commit the copies and the docx, and push)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
