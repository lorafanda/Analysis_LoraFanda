#!/usr/bin/env python3
"""
make_cohort_figure.py - FIG C.0, what the clustering cohort is made of.

    python make_cohort_figure.py                 newest cache in A, every cache in B
    python make_cohort_figure.py --version 11    pin panel A to concat_source_v11
    python make_cohort_figure.py --insert        also splice the block into the site

A  Per patient, the ERSP cubes that reached the cache - one per electrode x condition,
   in the FIG RT.1 layout: audio | picture | reading, stacked, total at the end. Each
   condition is drawn twice: solid for the cubes whose electrode is in the final gated
   cohort, pale for the ones that are not. "Not in the cohort" is the honest union of
   two different things, and the caption says so: an electrode can fail the activity
   gate, or be removed by a rule before the gate ever sees it (subdural grid,
   microwire, non-neural name, excluded patient, or a condition missing on disk).

B  The same cohort across every concat_source_v<N> on disk: patients by centre, patients
   by task language, and the native anatomy of the gated electrodes. This is the panel
   that says what actually changed between two versions, which the per-patient bars
   cannot.

RUN IT AFTER EVERY CACHE REBUILD. rebuild_concat_cache.py --apply calls this at the end,
so the figure is never older than the cohort it describes. It is also the first step of
the site phase of make_paper2_outputs.py.

WHERE THE THREE B QUANTITIES COME FROM
  centre, language   patient_meta.csv (make_patient_meta.py) - the language is read from
                     the behavioural filename or, where that file predates the
                     convention, from the stimuli; it is never inferred from the centre,
                     because PAT_3975 is a Geneva patient tested in German.
  native anatomy     the LM review bundle's contacts.json, the one place the BIDS
                     tissueLabel column is parsed. Missing for EL051/EL052, which are
                     not in the fsaverage coordinate file at all.
"""
