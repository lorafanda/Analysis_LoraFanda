def fig(num, title, bullets, name, alt, src=""):
    li = "\n".join(f"          <li>{b}</li>" for b in bullets)
    run = f'<div class="runid">{src}</div>' if src else ""
    return f"""    <figure>
      <div class="cap"><div class="fignum">FIG {num}{run}</div><h4>{title}</h4>
        <ul>
{li}
        </ul>
      </div>
      <div class="imgwrap"><img data-fig="{FIGROOT}/{name}" alt="{alt}"></div>
    </figure>"""


def para(*ps):
    return "\n".join(f"    <p>{p}</p>" for p in ps)


