#!/usr/bin/env python3
"""make_contact_review_block.py - the contacts to judge, at a size they can be judged at.

    python make_contact_review_block.py                 print the block
    python make_contact_review_block.py --insert        splice it into analysis_status.html
    python make_contact_review_block.py --insert --thresh 3

WHAT IT IS FOR. 148_contact_noise_audit.py says which contacts sit far from their own
montage; it cannot say whether they are broken. That needs eyes on the figures, and a
contact sheet of thumbnails is not enough - the first attempt at one was unreadable. So
each candidate gets a full-width row here: the clean ERSP, the HFA raster and the Signal
traces, with its numbers beside them, so a verdict can be given contact by contact.

WHAT IS AND IS NOT A CANDIDATE. Over `--thresh` on broadband sd or 70-150 Hz sd, as a
multiple of that patient's own montage median, and not already bad-listed. Contacts that
form the white-matter reference are included and marked: 140 writes no ERSP for them, so
those rows carry the Signal and HFA only, and they matter most - whatever they carry goes
into every other channel of that patient.

THE FIGURES ARE COPIED, not linked. The page resolves data-fig against
raw.githubusercontent.com/.../main, so a figure has to be committed; copying only the
candidates into outputs/_contact_review keeps that to a few dozen files instead of the
whole tree.
"""
from __future__ import annotations

import argparse
import csv
import glob
import os
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "functions"))

SITE = Path(os.environ.get("LF_SITE_DIR") or (Path.home() / "lorafanda.github.io")) / "analysis_status.html"
NOISE = HERE / "outputs" / "contact_noise"
TREES = (HERE / "outputs" / "03_ERSP-allchan-wm", HERE / "outputs" / "03_ERSP")
REVIEW = HERE / "outputs" / "_contact_review"
REPO_REL = "01_FBM_Analysis/outputs/_contact_review"
COND = "audio"
MAXW = 1200        # figures are shown at column width; the repo refuses >25 MB
BEGIN = "<!-- BEGIN contact review, generated by make_contact_review_block.py - do not hand-edit -->"
END = "<!-- END contact review -->"
WBEGIN = "<!-- BEGIN wm reference review, generated by make_contact_review_block.py - do not hand-edit -->"
WEND = "<!-- END wm reference review -->"
ANCHOR = "<h3"
REPORT = HERE / "outputs" / "03_ERSP" / "wm_reref_report.tsv"


def norm(s):
    return str(s).replace("_", "").replace("-", "").upper()


def drawn_contacts(pid):
    out = set()
    for t in TREES:
        for f in glob.glob(str(t / pid / "LM" / "PerTrial" / "Signal" / COND / "*.png")):
            m = re.search(r"_SIGtrials_(.+)\.png$", Path(f).name)
            if m:
                out.add(norm(m.group(1)))
        if out:
            break
    return out


def find(pid, ch, kind):
    pats = {"ersp": ("ERSP_clean", f"*_ERSP_{ch}_TN_CLEAN.png"),
            "hfa": ("PerTrial/HFA", f"*_HFAtrials_{ch}.png"),
            "sig": ("PerTrial/Signal", f"*_SIGtrials_{ch}.png")}
    sub, pat = pats[kind]
    for t in TREES:
        hits = sorted(glob.glob(str(t / pid / "LM" / sub / COND / pat)))
        if hits:
            return Path(hits[0])
    return None


def candidates(thresh, top):
    """The top `top` contacts of EVERY patient, not a single cohort-wide cut.

    A threshold alone hid most of what needs looking at: PAT_3965's worst is 28x and
    PAT_2868's is 2.3x, so any one number either floods one patient or silences another.
    Already bad-listed contacts are kept and marked - seeing them is how you confirm the
    list is right, and they were the first thing missing from this page.

    Only contacts that 140 actually drew are included, which is what keeps DC6, the X/E
    trigger blocks, MKR, ECG and Pleth out: they are in the TSV (Pleth measures a million
    times its montage) and none of them is a recording contact.
    """
    out = []
    for p in sorted(NOISE.glob("*_contact_noise.tsv")):
        rows = list(csv.DictReader(open(p, newline=""), delimiter="\t"))
        pid = rows[0]["patient"]
        drawn = drawn_contacts(pid)
        if not drawn:
            print(f"  [{pid}] no Signal plots in either tree - skipped")
            continue
        mine = []
        for r in rows:
            if norm(r["channel"]) not in drawn:
                continue
            sd, hg = float(r["sd_x"]), float(r["hg_x"])
            if max(sd, hg) < thresh:
                continue
            mine.append(dict(pid=pid, ch=r["channel"], sd=sd, hg=hg,
                             wm=r["is_wm"] == "1", bad=r["is_bad"] == "1",
                             m=max(sd, hg)))
        mine.sort(key=lambda d: -d["m"])
        out.extend(mine[:top])
    out.sort(key=lambda d: (d["pid"], -d["m"]))
    return out


def wm_ref_candidates(pid):
    """Every contact in the reference THE LAST RUN ACTUALLY USED, worst first.

    Not the anatomy flag: wm_reref_report.tsv records wm_channels_used per patient, which
    is the mean after the bad list has been taken out of it. These contacts get no ERSP in
    03_ERSP - 140 skips a reference contact from every product - so the rows here come from
    the 03_ERSP-allchan-wm tree, where 147 --keep-wm draws them as ordinary channels. That
    tree was built under whatever reference was configured AT THE TIME, so after a
    reference change these figures are the old view until 147 is run again.

    No threshold and no cut: the whole pool is shown. A reference contact's number is also
    attenuated, because 148 measures it after subtracting a mean that contains it (1/N of
    itself), so a quiet-looking member is not proof of a quiet member.
    """
    import csv as _csv
    used = []
    for r in _csv.DictReader(open(REPORT, newline="", encoding="utf-8"), delimiter="\t"):
        if r["patient_id"] == pid:
            used = [x for x in (r["wm_channels_used"] or "").split("|") if x]
    if not used:
        raise SystemExit(f"no wm_channels_used for {pid} in {REPORT}")
    p = NOISE / f"{pid}_contact_noise.tsv"
    noise = {}
    if p.exists():
        noise = {norm(r["channel"]): r for r in
                 csv.DictReader(open(p, newline=""), delimiter="\t")}
    out = []
    for u in used:
        r = noise.get(norm(u))
        sd = float(r["sd_x"]) if r else float("nan")
        hg = float(r["hg_x"]) if r else float("nan")
        out.append(dict(pid=pid, ch=u, sd=sd, hg=hg, wm=True,
                        bad=bool(r and r["is_bad"] == "1"),
                        m=(max(sd, hg) if r else -1.0)))
    out.sort(key=lambda d: -d["m"])
    return out


def build_wm(cands, pid):
    rows = []
    for c in cands:
        tag = ' · <b style="color:#c1121f">already bad-listed</b>' if c["bad"] else ""
        imgs = "".join(
            f'<figure style="margin:0;flex:1 1 0;min-width:0">'
            f'<img data-fig="{c["figs"][k]}" alt="{c["ch"]} {k}" '
            f'loading="lazy" decoding="async" '
            f'style="width:100%;height:auto;min-height:120px;'
            f'border:1px solid #e3e6ea;border-radius:6px">'
            f'<figcaption style="font-size:11px;color:#7c858e;margin-top:3px">{lab}</figcaption>'
            f'</figure>'
            for k, lab in (("ersp", "clean ERSP"), ("hfa", "HFA trials"),
                           ("sig", "Signal trials")) if c["figs"].get(k))
        miss = "" if imgs else ('<div style="font-size:12px;color:#c1121f">no figures: this '
                                'contact is not in the allchan-wm tree either</div>')
        num = ("not measured" if c["m"] < 0 else
               f'broadband <b>{c["sd"]:.2f}&times;</b> &nbsp;high gamma <b>{c["hg"]:.2f}&times;</b>')
        rows.append(
            f'<div style="margin:0 0 18px">'
            f'<div style="font-size:13px;margin:0 0 4px"><code>{c["ch"]}</code> '
            f'&nbsp;{num} the montage median{tag}</div>'
            f'<div style="display:flex;gap:10px;align-items:flex-start">{imgs}{miss}</div>'
            f'</div>')
    return f"""{WBEGIN}
<h3>{pid} &mdash; every contact in the white-matter reference</h3>
<p style="max-width:62em">All {len(cands)} contacts of the mean that the last 140 run
actually used (<code>wm_channels_used</code> in <code>wm_reref_report.tsv</code>, i.e.
after the bad list was removed from it), worst first. 140 writes no ERSP for a reference
contact, so these figures come from <code>03_ERSP-allchan-wm</code>, where
<code>147 --keep-wm</code> draws them as ordinary channels &mdash; under the reference that
was configured when that tree was built. Condition: {COND}.</p>
<p style="max-width:62em;color:#7c858e">Read the numbers with care here: 148 measures a
contact after subtracting a mean that contains it, so each member has about 1/{len(cands)}
of its own signal removed before it is measured. A low number is weaker evidence for a
reference contact than for an ordinary one. Whatever these contacts carry is subtracted
from every channel of the patient.</p>
{chr(10).join(rows)}
{WEND}"""


def stage(cands):
    """Copy each candidate's figures under outputs/_contact_review/<pid>/."""
    REVIEW.mkdir(parents=True, exist_ok=True)
    n = 0
    for c in cands:
        d = REVIEW / c["pid"]
        d.mkdir(exist_ok=True)
        c["figs"] = {}
        for kind in ("ersp", "hfa", "sig"):
            src = find(c["pid"], c["ch"], kind)
            if not src:
                continue
            dst = d / f"{c['ch']}_{kind}.png"
            if not dst.exists() or dst.stat().st_mtime < src.stat().st_mtime:
                # downscaled and quantised on the way in, not copied: the repo refuses a
                # commit over 25 MB and the originals are ~0.6 MB each. Resizing alone is
                # not enough - converting to RGB first threw away matplotlib's palette and
                # made the set BIGGER (39.5 -> 53.7 MB); the colour reduction is the win.
                from PIL import Image
                im = Image.open(src).convert("RGB")
                if im.width > MAXW:
                    im.thumbnail((MAXW, MAXW * 4), Image.LANCZOS)
                im.quantize(colors=256, method=Image.MEDIANCUT).save(
                    dst, "PNG", optimize=True)
                n += 1
            c["figs"][kind] = f"{REPO_REL}/{c['pid']}/{dst.name}"
    return n


def build(cands, thresh, top):
    by = {}
    for c in cands:
        by.setdefault(c["pid"], []).append(c)
    rows = []
    for pid, cs in by.items():
        rows.append(f'<h4 style="margin:22px 0 6px">{pid} '
                    f'<span style="font-weight:400;color:#7c858e">· {len(cs)} to judge</span></h4>')
        for c in cs:
            tag = ((' · <b style="color:#b8860b">in the WM reference</b>' if c["wm"] else "")
                   + (' · <b style="color:#c1121f">already bad-listed</b>' if c["bad"] else ""))
            miss = "" if c["figs"].get("ersp") else \
                ' · <span style="color:#7c858e">no ERSP: 140 writes none for a reference contact</span>'
            imgs = "".join(
                f'<figure style="margin:0;flex:1 1 0;min-width:0">'
                # lazy, or the browser asks for all ~590 figures at once and the page
                # never finishes loading - it timed out at 300 s before this was added
                f'<img data-fig="{c["figs"][k]}" alt="{c["ch"]} {k}" '
                f'loading="lazy" decoding="async" '
                f'style="width:100%;height:auto;min-height:120px;'
                f'border:1px solid #e3e6ea;border-radius:6px">'
                f'<figcaption style="font-size:11px;color:#7c858e;margin-top:3px">{lab}</figcaption>'
                f'</figure>'
                for k, lab in (("ersp", "clean ERSP"), ("hfa", "HFA trials"),
                               ("sig", "Signal trials")) if c["figs"].get(k))
            rows.append(
                f'<div style="margin:0 0 18px">'
                f'<div style="font-size:13px;margin:0 0 4px"><code>{c["ch"]}</code> '
                f'&nbsp;broadband <b>{c["sd"]:.1f}&times;</b> &nbsp;high gamma '
                f'<b>{c["hg"]:.1f}&times;</b> the montage median{tag}{miss}</div>'
                f'<div style="display:flex;gap:10px;align-items:flex-start">{imgs}</div>'
                f'</div>')
    return f"""{BEGIN}
<h3>Contacts to judge &mdash; the worst {top} of each patient</h3>
<p style="max-width:62em">Measured by <code>148_contact_noise_audit.py</code> on the
white-matter-referenced signal, which is the only place a noisy contact shows: the cubes
are dB re baseline and divide the noise out, the raw signal is dominated by the shared
reference, and <code>score_hg</code> is a within-channel z so every contact reads 1.0.
Each number is a multiple of <i>that patient's own</i> montage median &mdash; a broken
contact separates from its montage by an order of magnitude, so there is no threshold
that serves every patient. Contacts already on the bad list are shown and marked, so the list itself can be
checked. Condition: {COND}.</p>
<p style="max-width:62em;color:#7c858e">A large number is not a verdict. Of the first
eight looked at, only EL030 <code>aH_L11</code> &mdash; the one that was worst on
<i>broadband</i> rather than high gamma &mdash; actually looked broken; the rest were
fine-grained speckle on an otherwise ordinary contact.</p>
{chr(10).join(rows)}
{END}"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--insert", action="store_true")
    ap.add_argument("--thresh", type=float, default=1.5,
                    help="floor: below this a contact is not worth a row")
    ap.add_argument("--top", type=int, default=8,
                    help="how many of each patient's worst to show")
    ap.add_argument("--wm-ref", metavar="PID", default=None,
                    help="instead of the candidate block, emit one patient's WHOLE white-"
                         "matter reference (its own block, its own markers, the other one "
                         "is left alone)")
    a = ap.parse_args()
    if a.wm_ref:
        cands = wm_ref_candidates(a.wm_ref)
        n = stage(cands)
        print(f"{a.wm_ref}: {len(cands)} contacts in the reference, {n} figures copied "
              f"-> {REVIEW / a.wm_ref}")
        block, begin, end = build_wm(cands, a.wm_ref), WBEGIN, WEND
    else:
        cands = candidates(a.thresh, a.top)
        if not cands:
            raise SystemExit(f"nothing over {a.thresh}x - run 148_contact_noise_audit.py first")
        n = stage(cands)
        print(f"{len(cands)} candidates over {a.thresh}x, {n} figures copied -> {REVIEW}")
        block, begin, end = build(cands, a.thresh, a.top), BEGIN, END
    if not a.insert:
        print(block[:1500] + "\n...")
        return 0
    s = SITE.read_text(encoding="utf-8")
    if begin in s:
        i, j = s.index(begin), s.index(end) + len(end)
        s = s[:i] + block + s[j:]
        print("replaced the existing block")
    else:
        k = s.index('<section id="s1"')
        # AFTER the other generated block if it is already there, never before the first
        # <h3>: that <h3> can be inside the other block, and then the two sets of markers
        # interleave (BEGIN a, BEGIN b, END b, END a). Re-inserting the outer one would
        # silently take the inner one with it, which is how the WM block nearly went.
        other = WEND if begin is BEGIN else END
        j = s.find(other, k)
        if j != -1:
            at = j + len(other)
            s = s[:at] + "\n" + block + s[at:]
            print(f"inserted after the existing {other}")
        else:
            at = s.rindex("\n", 0, s.index(ANCHOR, k)) + 1
            s = s[:at] + block + "\n" + s[at:]
            print("inserted at the top of the s1 tab")
    SITE.write_text(s, encoding="utf-8")
    print("->", SITE)
    print(f"\ncommit and push the figures, or the page shows nothing:\n"
          f"  git add -f 01_FBM_Analysis/outputs/_contact_review\n"
          f'  git commit --only -- 01_FBM_Analysis/outputs/_contact_review -m "contact review figures"\n'
          f"  git push")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
