"""
make_patient_qc_tab.py - a tab of analysis_status.html with one sub-tab per patient: the
WM-referenced QC figures of the current 03_ERSP tree, as compressed copies the site can serve.

    python make_patient_qc_tab.py                       build the copies + the block (outputs/_status_png/patients/)
    python make_patient_qc_tab.py --insert              and splice it into the site (then: make_site_ui.py --insert)
    python make_patient_qc_tab.py --patients PAT_3455 PAT_3975 --insert    refresh only these (the rest keep theirs)
    python make_patient_qc_tab.py --max-ref 24          cap on reference contacts drawn per patient (default 24)

WHAT EACH PATIENT'S SUB-TAB SHOWS (one <h3> per patient; make_site_ui turns the h3s into the
sub-tab strip, so the top row of the tab is the patients)
  the run line     date, channels in / neural / used, trials used per condition, the reference (n and
                   the contacts), the bad list - from audit_140.tsv and wm_reref_report.tsv
  P.1  montage overview                   PerTrial/Report/<pid>_montage_overview.png
  P.2  PSD per shaft, raw and clean       PSD_raw | PSD_clean/<cond>/PSD/psd_by_shaft.png, three conditions
  P.3  the trial report per condition     PerTrial/Report/<pid>_<cond>_iqr_postDur_QC.png
  P.4  the reference contacts themselves  ERSP_noref | PerTrial/HFA_noref | PerTrial/Signal_noref/audio/
                                          <pid>_audio_NOREF_<ERSP|HFAtrials|SIGtrials>_<ch>.png for every contact
                                          in the white-matter mean, unreferenced (notch + baseline only; 140
                                          since 2026-10-13, or --wm-noref-only): a bad reference contact shows here
  P.5  the strongest audio responder      its HFA raster and ERSP (chosen from the cubes: the largest
                                          70-150 Hz response-half mean, bad-listed contacts excluded)

THE COPIES. WebP, quality 75, long side <= 1400 px (the montage overview <= 1600 px; its PNG is 16 MB
and the repo guard refuses files over 5 MB), under outputs/_status_png/patients/<pid>/. The originals
stay in the tree. A copy is refreshed when its source is newer; a patient's folder is emptied before
it is rebuilt so a rerun that renamed contacts leaves nothing behind. The site reads the copies from
GitHub main, so they have to be committed and pushed (about 1.5-3 MB per patient).
"""
