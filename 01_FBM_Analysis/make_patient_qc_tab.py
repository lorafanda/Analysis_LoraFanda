from pathlib import Path

import numpy as np
import pandas as pd
from PIL import Image

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "functions"))
import config as cfg                                                  # noqa: E402

TREE = ROOT / "outputs" / cfg.ERSP_TREE
AUDIT = TREE / "audit_140.tsv"
REPORT = TREE / "wm_reref_report.tsv"
OUT = ROOT / "outputs" / "_status_png" / "patients"
FIGROOT = "01_FBM_Analysis/outputs/_status_png/patients"
SITE = Path("C:/Users/fanda/lorafanda.github.io/analysis_status.html")
CONDS = ("audio", "picture", "reading")
ACC = "#2a7f62"

B_SEC = "<!-- BEGIN patient qc tab, generated by make_patient_qc_tab.py - do not hand-edit -->"
E_SEC = "<!-- END patient qc tab -->"
B_NAV = "<!-- BEGIN patient qc nav -->"
E_NAV = "<!-- END patient qc nav -->"
NAV = ('    <button class="npq" data-t="pqc"><span class="dot" style="background:#2a7f62"></span>'
       "Patients &middot; QC figures</button>")

DF_HZ = 1000.0 / 256.0
FREQ = np.arange(103) * DF_HZ
HARM = set()
for _h in (50, 100, 150, 200, 250, 300, 350, 400):
    HARM |= {int(round(_h / DF_HZ)) + d for d in (-1, 0, 1)}
HG_ROWS = [r for r in range(103) if 70 <= FREQ[r] < 150 and r not in HARM]


def norm(s) -> str:
    return "" if s is None else str(s).replace("_", "").replace("-", "").upper()


Image.MAX_IMAGE_PIXELS = None          # the montage overviews are our own figures, up to 340 Mpx
MAX_MPX = 400


def webp(src: Path, dst: Path, max_side: int, quality: int = 75) -> bool:
    """Compressed copy; False when the source is missing or too large to decode. Refreshed only
    when the source is newer."""
    if not src.exists():
        return False
    if dst.exists() and dst.stat().st_mtime >= src.stat().st_mtime:
        return True
    dst.parent.mkdir(parents=True, exist_ok=True)
    im = Image.open(src)
    if im.size[0] * im.size[1] > MAX_MPX * 1e6:
        print(f"    [skip] {src.name}: {im.size[0] * im.size[1] / 1e6:.0f} Mpx, above the {MAX_MPX} Mpx cap")
        return False
    try:
        im = im.convert("RGB")
        im.thumbnail((max_side, max_side), Image.LANCZOS)
        im.save(dst, "WEBP", quality=quality, method=4)
    except MemoryError:
        print(f"    [skip] {src.name}: out of memory while decoding")
        return False
    return True


def signal_dir(lm: Path) -> Path:
    """The Signal figures: PerTrial/Signal since 2026-10-02, Signal before a patient was moved."""
    d = lm / "PerTrial" / "Signal"
    return d if d.is_dir() else lm / "Signal"


def strongest_audio_contact(pid: str, bad: set) -> tuple[str, float] | None:
    """The contact with the largest 70-150 Hz response-half mean in the audio cube (bad list excluded)."""
    best = None
    for f in sorted(glob.glob(str(TREE / pid / "LM" / "ERSP_matrix" / "audio" / "*_TN.npy"))):
        ch = os.path.basename(f).split("_ERSP_")[1][:-7]
        if norm(ch) in bad:
            continue
        try:
            A = np.load(f, mmap_mode="r")
            v = float(np.asarray(A[HG_ROWS, 150:]).mean())
        except Exception:                                   # noqa: BLE001
            continue
        if best is None or v > best[1]:
            best = (ch, v)
    return best


NOREF = (("ersp", "ERSP_noref", "_NOREF_ERSP_", "_TN.png", "ERSP"),
         ("hfa", cfg.HFA_DIR + "_noref", "_NOREF_HFAtrials_", ".png", "HFA raster"),
         ("sig", getattr(cfg, "SIGNAL_DIR", "Signal") + "_noref", "_NOREF_SIGtrials_", ".png", "signal, trial by trial"))


def noref_index(pid: str) -> dict:
    """kind -> {norm(contact): (path, label)}: the unreferenced figures 140 writes for the contacts of
    the white-matter mean (write_wm_noref_figures, 2026-10-13), audio block."""
    out = {}
    for kind, sub, tag, tail, label in NOREF:
        d = TREE / pid / "LM" / sub / "audio"
        m = {}
        if d.is_dir():
            for f in os.listdir(d):
                if f.endswith(tail) and tag in f:
                    m[norm(f.split(tag)[1][:-len(tail)])] = (d / f, label)
        out[kind] = m
    return out


def fig(num: str, title: str, items: list, note: str = "") -> str:
    """One figure block with a grid of (webp path, caption) pairs."""
    cells = "\n".join(f'        <figure class="pqc-cell" style="margin:0"><div class="imgwrap" style="margin:0"><img data-fig="{FIGROOT}/{p}" alt="{c}"></div>'
                      f'<figcaption style="font-size:12px;color:var(--muted);margin-top:3px">{c}</figcaption></figure>' for p, c in items)
    nt = f'<div class="runid">{note}</div>' if note else ""
    return (f'    <div class="pqc-fig" style="margin:10px 0 18px"><div class="cap"><div class="fignum">FIG {num}{nt}</div><h4>{title}</h4></div>\n'
            f'      <div class="pqc-grid" style="display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:10px;margin:6px 0 14px">\n{cells}\n      </div></div>')


def build_patient(pid: str, a: pd.Series, r: pd.Series | None, max_ref: int, examples: dict) -> tuple[str, list, dict]:
    """(html, missing, stats) for one patient; writes the WebP copies."""
    pdir = OUT / pid
    missing, nbytes, nfiles = [], 0, 0

    def copy(src: Path, name: str, max_side: int = 1400) -> str | None:
        nonlocal nbytes, nfiles
        dst = pdir / name
        if webp(src, dst, max_side):
            nbytes += dst.stat().st_size
            nfiles += 1
            return f"{pid}/{name}"
        missing.append(str(src.relative_to(TREE)))
        return None

    lm = TREE / pid / "LM"
    rep_dir = Path(cfg.product_dir(lm, "Report"))
    hfa_dir = Path(cfg.product_dir(lm, "HFA"))
    bad = {norm(x) for x in cfg.bad_channels_manual.get(pid, [])}
    wm_used = [x for x in str(r["wm_channels_used"] if r is not None else "").split("|") if x]
    blocks = []
    # P.1 montage
    p = copy(rep_dir / f"{pid}_montage_overview.png", "montage.webp", 1600)
    if p:
        blocks.append(fig("P.1", "Montage overview", [(p, "all channels, the run's montage")], f"{pid}_montage_overview.png"))
    # P.2 PSD raw / clean per condition
    items = []
    for c in CONDS:
        for kind in ("raw", "clean"):
            p = copy(lm / f"PSD_{kind}" / c / "PSD" / "psd_by_shaft.png", f"psd_{c}_{kind}.webp", 1400)
            if p:
                items.append((p, f"{c} &middot; {kind}"))
    if items:
        blocks.append(fig("P.2", "PSD per shaft, raw and after the notch, per condition block",
                          items, "PSD_raw | PSD_clean/&lt;cond&gt;/PSD/psd_by_shaft.png"))
    # P.3 trial report
    items = []
    for c in CONDS:
        p = copy(rep_dir / f"{pid}_{c}_iqr_postDur_QC.png", f"iqr_{c}.webp", 1400)
        if p:
            items.append((p, f"{c}"))
    if items:
        blocks.append(fig("P.3", "Trial report: post-stimulus durations and the IQR rule, per condition", items,
                          f"{cfg.REPORT_DIR}/{pid}_&lt;cond&gt;_iqr_postDur_QC.png"))
    # P.4 the reference contacts themselves, unreferenced: the NOREF figures of 140 (2026-10-13)
    nidx = noref_index(pid)
    # the numbers 140 writes beside the figures: per contact, the 70-150 Hz mean in the response half (audio)
    summ = {}
    st = lm / "ERSP_noref" / "audio" / f"{pid}_audio_NOREF_summary.tsv"
    if st.exists():
        for rr in pd.read_csv(st, sep="\t").itertuples():
            summ[norm(rr.contact)] = (float(rr.hg_resp_db), float(rr.hg_absmax_db))
    items, lost = [], []
    for ch in wm_used[:max_ref]:
        got = 0
        num = summ.get(norm(ch))
        tag = f" &middot; HG response {num[0]:+.2f} dB, peak |{num[1]:.1f}|" if num else ""
        for kind, _sub, _tag, _tail, label in NOREF:
            hit = nidx[kind].get(norm(ch))
            if not hit:
                continue
            p = copy(hit[0], f"ref_{norm(ch)}_{kind}.webp", 900)
            if p:
                items.append((p, f"{ch} &middot; {label}{tag if kind == 'ersp' else ''}"))
                got += 1
        if not got:
            lost.append(ch)
    note = f"{len(wm_used)} contacts in the white-matter mean; notch and per-trial baseline only, no reference"
    if summ:
        worst = max(summ.items(), key=lambda kv: abs(kv[1][0]))
        note += f"; audio response half at 70&ndash;150 Hz: {min(v[0] for v in summ.values()):+.2f} to {max(v[0] for v in summ.values()):+.2f} dB, largest |mean| {worst[0]} ({worst[1][0]:+.2f} dB)"
    if len(wm_used) > max_ref:
        note += f"; the first {max_ref} drawn, the rest in the tree"
    if lost:
        note += f"; not drawn yet: {' '.join(lost)}"
    if items:
        blocks.append(fig("P.4", "The reference contacts themselves, unreferenced (audio block): ERSP, HFA raster and signal per contact", items, note))
    elif wm_used:
        blocks.append('    <div class="pqc-fig" style="margin:10px 0 18px"><div class="cap"><div class="fignum">FIG P.4'
                      f'<div class="runid">{len(wm_used)} contacts in the white-matter mean: {" ".join(wm_used)}</div></div>'
                      '<h4>The reference contacts themselves: no figure yet</h4></div>'
                      '<p style="font-size:13px;color:var(--muted)">Since 2026-10-13 140 draws the contacts of the white-matter '
                      'mean unreferenced (notch and per-trial baseline only) into <code>ERSP_noref/</code>, '
                      '<code>PerTrial/HFA_noref/</code> and <code>PerTrial/Signal_noref/</code>; this patient has not been run '
                      'since. <code>140_ersp_pipeline.py --patient &lt;pid&gt; --wm-noref-only</code> draws just these.</p></div>')
    # P.5 the strongest audio responder
    key = f"{pid}"
    ex = examples.get(key)
    cubes = sorted(glob.glob(str(TREE / pid / "LM" / "ERSP_matrix" / "audio" / "*_TN.npy")))
    newest = max((os.path.getmtime(f) for f in cubes), default=0)
    if not ex or ex.get("newest") != newest:
        best = strongest_audio_contact(pid, bad)
        ex = {"contact": best[0], "hg_resp_db": round(best[1], 3), "newest": newest} if best else None
        examples[key] = ex
    if ex:
        ch = ex["contact"]
        items = []
        p = copy(hfa_dir / "audio" / f"{pid}_audio_WM_HFAtrials_{ch}.png", f"example_hfa_{norm(ch)}.webp", 1400)
        if p:
            items.append((p, f"{ch} &middot; HFA raster, audio"))
        p = copy(lm / "ERSP" / "audio" / f"{pid}_audio_WM_ERSP_{ch}_TN.png", f"example_ersp_{norm(ch)}.webp", 1400)
        if p:
            items.append((p, f"{ch} &middot; ERSP, audio"))
        if items:
            blocks.append(fig("P.5", f"The strongest audio responder: {ch} ({ex['hg_resp_db']:+.2f} dB at 70&ndash;150 Hz in the response half)",
                              items, "largest response-half HG mean of the audio cubes, bad-listed contacts excluded"))
    # the run line
    try:
        n_used = int(float(r["n_channels_used"])) if r is not None else 0
    except (TypeError, ValueError):
        n_used = 0
    used = f", {n_used} used" if n_used > 0 else ""
    tr = " / ".join(str(a.get(f"{c}_trials_used", "")) for c in CONDS)
    run = str(a.get("run_start", ""))[:16]
    line = (f'    <p class="pqc-run" style="font-size:13px;line-height:1.5"><b>run</b> {run} &middot; <b>channels</b> {a.get("ch_in", "")} in, {a.get("ch_neural", "")} neural'
            f'{used} &middot; <b>trials used</b> {tr} (audio / picture / reading)'
            f' &middot; <b>reference</b> WM {len(wm_used)}: {" ".join(wm_used) or "&ndash;"}'
            f' &middot; <b>bad list</b> {str(a.get("bad_list", "")) or "&ndash;"}</p>')
    html = (f'    <div class="pq-pane" id="pq-pane-{pid}">\n    <h3 id="pqc-{pid}">{pid}</h3>\n{line}\n'
            + "\n".join(blocks) + "\n    </div>")
    return html, missing, dict(files=nfiles, mb=nbytes / 1e6, blocks=len(blocks))


def build(patients: list, max_ref: int) -> tuple[str, dict]:
    audit = pd.read_csv(AUDIT, sep="\t", dtype=str).fillna("").set_index("patient")
    rep = pd.read_csv(REPORT, sep="\t", dtype=str).fillna("")
    rep = rep.drop_duplicates("patient_id", keep="last").set_index("patient_id")
    ex_path = OUT / "example_contacts.json"
    examples = json.loads(ex_path.read_text(encoding="utf-8")) if ex_path.exists() else {}
    OUT.mkdir(parents=True, exist_ok=True)
    parts, report, done = [], {}, []
    for pid in patients:
        if pid not in audit.index:
            print(f"  !! {pid}: not in the audit, skipped")
            continue
        html, missing, st = build_patient(pid, audit.loc[pid], rep.loc[pid] if pid in rep.index else None, max_ref, examples)
        parts.append(html)
        done.append(pid)
        report[pid] = dict(st, missing=missing)
        print(f"  {pid:<9} {st['blocks']} blocks, {st['files']:>3} files, {st['mb']:.2f} MB" + (f"  missing {len(missing)}" if missing else ""), flush=True)
    ex_path.write_text(json.dumps(examples, indent=1), encoding="utf-8")
    stamp = time.strftime("%d %B %Y")
    head = [B_SEC, '  <section id="pqc">',
            f'    <div class="eyebrow" style="color:{ACC}">Patients &middot; QC figures, {stamp}</div>',
            "    <h2>Every patient's WM-referenced QC figures, one sub-tab each</h2>",
            '    <p class="lead">The figures the review of a patient is made on, straight from the current '
            f"<code>{cfg.ERSP_TREE}</code> tree, as compressed copies: the montage, the PSD per shaft before and after the "
            "notch, the trial report, the cleaned signal of every contact in the white-matter reference, and the strongest "
            "audio responder's HFA raster and ERSP. Pick a patient on the strip. A reference contact that carries a line "
            "or broadband noise shows in P.4 before it shows anywhere else; the per-contact HFA rasters and ERSPs of the "
            "whole montage are in the tree and in the LM visualizer's review mode, not here.</p>",
            # the patients as a row of tabs. The class pf-bar tells make_site_ui's runtime that this tab
            # brings its own strip (it would otherwise fold 30 headings into a dropdown); the buttons and
            # panes carry their own names (pq-) so the paper tab's bar script leaves them alone.
            "    <style>#pqc .pf-bar button.on{background:" + ACC + ";border-color:" + ACC + "}"
            "#pqc .pq-pane{display:none}#pqc .pq-pane.on{display:block}</style>",
            '    <div class="pf-bar pq-bar">',
            "\n".join('      <button type="button" data-pq="%s"%s>%s</button>' % (p, ' class="on"' if i == 0 else "", p)
                      for i, p in enumerate(done)),
            "    </div>"]
    body = "\n".join(parts).replace(f'<div class="pq-pane" id="pq-pane-{done[0]}">', f'<div class="pq-pane on" id="pq-pane-{done[0]}">', 1) if done else ""
    tail = ['    <script>(function(){const sec=document.getElementById("pqc");if(!sec)return;const bar=sec.querySelector(".pq-bar");',
            '      function show(k,push){sec.querySelectorAll(".pq-pane").forEach(p=>p.classList.toggle("on",p.id==="pq-pane-"+k));',
            '        bar.querySelectorAll("button").forEach(b=>b.classList.toggle("on",b.dataset.pq===k));',
            '        if(push)history.replaceState(null,"",location.pathname+location.search+"#pqc-"+k);}',
            '      bar.querySelectorAll("button").forEach(b=>{b.onclick=()=>show(b.dataset.pq,true);});',
            '      const h=location.hash||"";if(h.indexOf("#pqc-")===0){const k=h.slice(5);if(sec.querySelector("#pq-pane-"+k))show(k,false);}',
            '    })();</script>',
            "  </section>", E_SEC]
    return "\n".join(head) + "\n" + body + "\n" + "\n".join(tail), report


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--patients", nargs="*", help="only these (default: every patient of the audit, in its order)")
    ap.add_argument("--max-ref", type=int, default=24)
    ap.add_argument("--insert", action="store_true")
    a = ap.parse_args()
    audit = pd.read_csv(AUDIT, sep="\t", dtype=str).fillna("")
    patients = a.patients or [p for p, s in zip(audit["patient"], audit["status"]) if s == "ok"]
    html, report = build(patients, a.max_ref)
    (OUT / "webblock_patient_qc.html").write_text(html, encoding="utf-8")
    tot_mb = sum(v["mb"] for v in report.values())
    tot_f = sum(v["files"] for v in report.values())
    miss = {p: v["missing"] for p, v in report.items() if v["missing"]}
    print(f"-> {OUT / 'webblock_patient_qc.html'}   {len(report)} patients, {tot_f} copies, {tot_mb:.1f} MB")
    if miss:
        print("missing sources:")
        for p, m in miss.items():
            print(f"   {p}: {', '.join(m[:4])}{' ...' if len(m) > 4 else ''}")
    if not a.insert:
        print("\n(pass --insert to splice it into the site)")
        return 0
    s = SITE.read_text(encoding="utf-8")
    if B_SEC in s and E_SEC in s:
        i, j = s.index(B_SEC), s.index(E_SEC) + len(E_SEC)
        s = s[:i] + html + s[j:]
        print("replaced the existing patient qc section")
    else:
        anchor = '  <section id="caveats">'
        if anchor not in s:
            raise SystemExit("anchor section not found")
        i = s.index(anchor)
        s = s[:i] + html + "\n\n" + s[i:]
        print("inserted the patient qc section before #caveats")
    # the nav button: once. make_site_ui.py --insert regroups the nav and keeps the button but not
    # these markers, so the test is the button itself, not the markers.
    if 'data-t="pqc"' in s:
        print("nav button already there (make_site_ui.py keeps it when it regroups the nav)")
    elif B_NAV in s and E_NAV in s:
        i, j = s.index(B_NAV), s.index(E_NAV) + len(E_NAV)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + s[j:]
    else:
        anchor = '    <button class="n5" data-t="caveats">'
        if anchor not in s:
            raise SystemExit("nav anchor not found")
        i = s.index(anchor)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + "\n" + s[i:]
    SITE.write_text(s, encoding="utf-8")
    print(f"-> {SITE}   (now: python ../02_FBM_Clustering/make_site_ui.py --insert, then commit the copies and push)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
