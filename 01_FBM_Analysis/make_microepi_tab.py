def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--insert", action="store_true")
    a = ap.parse_args()

    OUT.mkdir(parents=True, exist_ok=True)
    missing = []
    for name, src in FIGS.items():
        if src is None:
            if not (OUT / name).exists():
                missing.append(f"{name}  <-  (expected already in microepi_status)")
            continue
        if src.exists():
            shutil.copy2(src, OUT / name)
        else:
            missing.append(f"{name}  <-  {src}")
    if missing:
        print("MISSING FIGURES - the tab would render placeholders:")
        for m in missing:
            print(f"   {m}")
    print(f"copied {len(FIGS) - len(missing)} figures -> {OUT}")

    html = build()
    out = OUT / "webblock_microepi.html"
    out.write_text(html, encoding="utf-8")
    print(f"-> {out}   ({len(html):,} chars)")
    if not a.insert:
        print("\n(pass --insert to splice it into the site)")
        return 0

    s = SITE.read_text(encoding="utf-8")
    if B_SEC in s and E_SEC in s:
        i, j = s.index(B_SEC), s.index(E_SEC) + len(E_SEC)
        s = s[:i] + html + s[j:]
        print("replaced the existing microepi section")
    else:
        anchor = '  <section id="caveats">'
        if anchor not in s:
            raise SystemExit("anchor section not found")
        i = s.index(anchor)
        s = s[:i] + html + "\n\n" + s[i:]
        print("inserted the microepi section before #caveats")
    if B_NAV in s and E_NAV in s:
        i, j = s.index(B_NAV), s.index(E_NAV) + len(E_NAV)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + s[j:]
    else:
        anchor = '    <button class="n5" data-t="caveats">'
        if anchor not in s:
            raise SystemExit("anchor nav button not found")
        i = s.index(anchor)
        s = s[:i] + B_NAV + "\n" + NAV + "\n    " + E_NAV + "\n" + s[i:]
        print("inserted the microepi nav button")
    if ".ne .dot" not in s:
        k = s.index("  .nk .dot")
