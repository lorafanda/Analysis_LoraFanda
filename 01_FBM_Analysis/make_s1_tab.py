def li(*items: str) -> str:
    return "".join(f"<li>{x}</li>" for x in items)


def ul(*items: str, cls: str = "") -> str:
    return f'<ul{(" class=" + chr(34) + cls + chr(34)) if cls else ""}>{li(*items)}</ul>'


