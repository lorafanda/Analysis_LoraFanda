def copy_figs() -> list[str]:
    OUT.mkdir(parents=True, exist_ok=True)
    missing = []
    for name, src in FIGS.items():
        if src is None:
            if not (OUT / name).exists():
                missing.append(f"{name}  <-  (expected already in _status_png)")
            continue
        if not src.exists():
            missing.append(f"{name}  <-  {src}")
            continue
        if src.stat().st_size > MAX_FIG_MB * 1e6:
            missing.append(f"{name}  <-  {src} ({src.stat().st_size / 1e6:.1f} MB, above the commit guard)")
            continue
        shutil.copy2(src, OUT / name)
        print(f"  copied {name}  <-  {src.relative_to(ROOT)}  ({src.stat().st_size / 1e3:.0f} kB)")
    return missing


def insert(block: str) -> None:
    s = SITE.read_text(encoding="utf-8")
    if B_SEC in s and E_SEC in s:
        i, j = s.index(B_SEC), s.index(E_SEC) + len(E_SEC)
        s = s[:i] + block.rstrip("\n") + s[j:]
        print("replaced the generated block")
    else:
        i = s.index('  <section id="s1">')
        j = s.index(STAGE2, i)
        s = s[:i] + block + "\n" + s[j:]
        print("replaced the hand-written <section id=\"s1\"> block")
    SITE.write_text(s, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--insert", action="store_true")
    a = ap.parse_args()
    missing = copy_figs()
    for m in missing:
        print("  MISSING", m)
    audit = read_audit()
    block = build(audit)
    print(f"block: {len(block):,} chars · patients in table: {0 if audit is None else len(audit)}")
    if a.insert:
        insert(block)
        print(f"wrote {SITE}")
    else:
        print("(pass --insert to splice it into the site)")
    return 0


