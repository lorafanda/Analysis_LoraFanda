def read_audit() -> pd.DataFrame | None:
    if not AUDIT.exists():
        return None
    return pd.read_csv(AUDIT, sep="\t", dtype=str).fillna("")


def ref_short(r) -> str:
    ref = r["reference"]
    if ref.startswith("per-grid CAR"):
        return "grid CAR"
    if ref.startswith("whole-recording CAR"):
        return "whole CAR"
    if r["system"] == "MicroEPI":
        return f"WM {r['wm_n']} (WM kept as data)"
    return f"WM {r['wm_n']}"


def status_short(r) -> str:
    s = r["status"]
    if r["log"] == "NOT RUN":
        return "not run"
    return "ok" if s == "ok" else s.split(":")[0]


def patient_table(a: pd.DataFrame) -> str:
    head = ("<tr><th>patient</th><th>sys</th><th>run</th><th>crop (s)</th><th>ref</th><th>bad</th><th>unk</th>"
            "<th>notch</th><th>trials a / p / r</th><th>cubes / cond</th><th>status</th></tr>")
    rows = []
    for _, r in a.iterrows():
        tr = " / ".join(str(r[f"{c}_trials_used"] or "–") for c in ("audio", "picture", "reading"))
        cubes = "/".join(str(r[f"{c}_cubes"] or "0") for c in ("audio", "picture", "reading"))
        run = r["run_start"][5:] if r["run_start"] else "–"
        rows.append(f"<tr><td><b>{_e(r['patient'])}</b></td><td>{_e(r['system'])}</td><td>{_e(run)}</td>"
                    f"<td>{_e(r['crop_cfg'].replace(' s', '') or '–')}</td><td>{_e(ref_short(r))}</td>"
                    f"<td>{_e(r['bad_listed_n'])}</td><td>{_e(r['unknown_dropped'] or '0')}</td>"
                    f"<td>{_e(r['notch_method'])}{' · shaft' if r['notch_scope'] == 'per shaft' else ''}</td>"
                    f"<td>{_e(tr)}</td><td>{_e(cubes)}</td><td>{_e(status_short(r))}</td></tr>")
    return f'<table class="sum" style="margin:8px 0;font-size:12px">{head}{"".join(rows)}</table>'


def run_status(a: pd.DataFrame | None) -> str:
    if a is None:
        return ul("audit table missing: run <code>141_audit_140.py</code>")
    ran = a[a["log"] != "NOT RUN"]
    ok = ran[ran["status"] == "ok"]
    n_cubes = sum(max(int(r[f"{c}_cubes"] or 0) for c in ("audio", "picture", "reading")) for _, r in ran.iterrows())
    not_run = [p for p in a[a["log"] == "NOT RUN"]["patient"]]
    bad = [f"{r['patient']}: {r['status']}" for _, r in ran.iterrows() if r["status"] != "ok"]
    days = sorted({r["run_start"][:10] for _, r in ran.iterrows() if r["run_start"]})
    shapes = sorted({s for s in ran["shapes"] if s})
    return ul(
        f"patients in <code>cfg.patient_ids</code>: <b>{len(a)}</b> · run: <b>{len(ran)}</b> ({', '.join(days)}) · ok: <b>{len(ok)}</b>"
        + (f" · not run: {', '.join(not_run)}" if not_run else ""),
        "producer: <code>01_FBM_Analysis/140_ersp_pipeline.py --patient &lt;id&gt;</code> (one process per patient; notebook 140 = same code)",
        f"contacts with cubes: <b>{n_cubes}</b> · cube shape: {', '.join(shapes) or '–'} (freq × warped time) · fmax <b>400 Hz</b>",
        "errors: " + ("; ".join(_e(b) for b in bad) if bad else "none"),
        "table: <code>outputs/04_ersp_LM/audit_140.tsv</code> / <code>.md</code> (<code>141_audit_140.py</code>) - one row per patient, 103 columns",
    )


